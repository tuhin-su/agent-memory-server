#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────
#  Memory Server — Interactive Setup
#  Run once before first `docker compose up`
#  Usage: bash setup.sh
# ─────────────────────────────────────────────────────────────────
set -e
cd "$(dirname "$0")"

# ── colours ──────────────────────────────────────────────────────
B='\033[1m'; G='\033[0;32m'; Y='\033[1;33m'
C='\033[0;36m'; R='\033[0;31m'; N='\033[0m'

banner() { echo -e "\n${C}${B}▶ $*${N}"; }
ok()     { echo -e "  ${G}✔ $*${N}"; }
warn()   { echo -e "  ${Y}⚠ $*${N}"; }
ask()    { local __v; read -rp "  $1" __v; printf '%s' "${__v:-$2}"; }

echo -e "${C}${B}"
echo "╔══════════════════════════════════════════╗"
echo "║   Memory Server — First-Time Setup       ║"
echo "╚══════════════════════════════════════════╝${N}"
echo

# ── check openssl ─────────────────────────────────────────────────
if ! command -v openssl &>/dev/null; then
  echo -e "${R}Error: openssl not found. Install it and re-run.${N}"
  exit 1
fi

# ── existing .env guard ───────────────────────────────────────────
if [ -f .env ]; then
  warn ".env already exists."
  yn=$(ask "Overwrite? [y/N]: " "N")
  [[ "$yn" =~ ^[Yy]$ ]] || { echo "  Aborted — existing .env kept."; exit 0; }
  echo
fi

# ═══════════════════════════════════════════════════════════════════
banner "Generating secure tokens (openssl rand)"
# ═══════════════════════════════════════════════════════════════════
ADMIN_TOKEN=$(openssl rand -base64 32 | tr -d '\n')
POSTGRES_PASSWORD=$(openssl rand -hex 20)
ok "ADMIN_TOKEN and POSTGRES_PASSWORD generated"

# ═══════════════════════════════════════════════════════════════════
banner "API Network Settings"
# ═══════════════════════════════════════════════════════════════════
API_PORT=$(ask "API port [8080]: " "8080")
API_HOST=$(ask "API bind host [0.0.0.0]: " "0.0.0.0")
ok "API will listen on ${API_HOST}:${API_PORT}"

# ═══════════════════════════════════════════════════════════════════
banner "Data Storage"
# ═══════════════════════════════════════════════════════════════════
echo "  Choose how data is stored:"
echo "    ${B}Named volume${N} (Docker manages it, auto-created):  memdata"
echo "    ${B}Host folder${N}  (absolute path):                    /home/you/data"
echo "    ${B}Host folder${N}  (relative path):                    ./data"
echo
DATA_VOLUME=$(ask "DATA_VOLUME [memdata]: " "memdata")

if [[ "$DATA_VOLUME" == /* ]] || [[ "$DATA_VOLUME" == ./* ]]; then
  # ── bind-mount path ──────────────────────────────────────────────
  mkdir -p "$DATA_VOLUME"
  ok "Host folder created/confirmed: $(realpath "$DATA_VOLUME")"
  VOLUME_NOTE="bind-mount (host folder)"
else
  # ── named Docker volume ──────────────────────────────────────────
  ok "Named Docker volume '${DATA_VOLUME}' — Docker will create it automatically."
  VOLUME_NOTE="named Docker volume"
fi

# ═══════════════════════════════════════════════════════════════════
banner "Embedding Provider"
# ═══════════════════════════════════════════════════════════════════
echo "  ${B}ollama${N} — local LLM server (default)"
echo "  ${B}none${N}   — disable embeddings (keyword-only search)"
echo
EMBED_PROVIDER=$(ask "EMBED_PROVIDER [ollama]: " "ollama")

OLLAMA_URL="http://host.docker.internal:11434"
EMBED_MODEL="nomic-embed-text"
EMBED_DIM="768"

if [ "$EMBED_PROVIDER" = "ollama" ]; then
  OLLAMA_URL=$(ask "OLLAMA_URL [$OLLAMA_URL]: " "$OLLAMA_URL")
  EMBED_MODEL=$(ask "EMBED_MODEL [$EMBED_MODEL]: " "$EMBED_MODEL")
  EMBED_DIM=$(ask "EMBED_DIM   [$EMBED_DIM]: " "$EMBED_DIM")
  ok "Ollama: ${OLLAMA_URL} model=${EMBED_MODEL} dim=${EMBED_DIM}"
  echo
  warn "Make sure the model is pulled on your host:"
  echo "       ollama pull ${EMBED_MODEL}"
else
  ok "Embeddings disabled — search will use keyword (BM25) only"
fi

# ═══════════════════════════════════════════════════════════════════
banner "Optional Tuning"
# ═══════════════════════════════════════════════════════════════════
MAX_FILE_BYTES=$(ask "MAX_FILE_BYTES [2000000]: " "2000000")
ok "Max file size: ${MAX_FILE_BYTES} bytes"

# ═══════════════════════════════════════════════════════════════════
banner "Writing .env"
# ═══════════════════════════════════════════════════════════════════
cat > .env <<EOF
# Generated by setup.sh on $(date -u +"%Y-%m-%d %H:%M UTC")

# ── Secrets ───────────────────────────────────────────────────────
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
ADMIN_TOKEN=${ADMIN_TOKEN}

# ── API listen address ────────────────────────────────────────────
API_HOST=${API_HOST}
API_PORT=${API_PORT}

# ── Data storage (${VOLUME_NOTE}) ─────────────────────────────────
# Named Docker volume (auto-managed): DATA_VOLUME=memdata
# Absolute host path (bind-mount):    DATA_VOLUME=/home/you/data
# Relative host path (bind-mount):    DATA_VOLUME=./data
DATA_VOLUME=${DATA_VOLUME}

# ── Embedding ─────────────────────────────────────────────────────
EMBED_PROVIDER=${EMBED_PROVIDER}
OLLAMA_URL=${OLLAMA_URL}
EMBED_MODEL=${EMBED_MODEL}
EMBED_DIM=${EMBED_DIM}

# ── Optional tuning ───────────────────────────────────────────────
MAX_FILE_BYTES=${MAX_FILE_BYTES}
EOF

ok ".env written"

# ═══════════════════════════════════════════════════════════════════
#  Summary
# ═══════════════════════════════════════════════════════════════════
echo
echo -e "${C}${B}═══════════════════════════════════════════${N}"
echo -e "${G}${B}  ✅  Setup complete!${N}"
echo -e "${C}${B}═══════════════════════════════════════════${N}"
echo
echo -e "  ${B}ADMIN_TOKEN${N} (save this — shown once):"
echo -e "  ${Y}${ADMIN_TOKEN}${N}"
echo
echo -e "  ${B}Next steps:${N}"
echo "   1. Start server:   docker compose up -d"
echo "   2. Start web UI:   ./memory-ui/start.sh"
echo "   3. Open browser:   http://localhost:${API_PORT}"
echo "   4. Connect UI to:  http://localhost:${API_PORT}"
echo
warn "Never commit .env — it contains your secrets."
echo
